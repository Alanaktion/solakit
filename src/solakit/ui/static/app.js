/* UI behavior only. Credentials never enter browser storage or application JS. */
(() => {
  let started = 0;
  let timer;
  let events;
  const form = () => document.getElementById("composer");
  function jobSchedule() {
    const kind = document.getElementById("job-schedule-kind");
    if (!kind) return;
    const once = kind.value === "once";
    for (const [id, visible] of [["job-cron-fields", !once], ["job-once-fields", once], ["job-cron-options", !once]]) {
      const group = document.getElementById(id);
      group.hidden = !visible;
      group.querySelectorAll("input").forEach(input => {
        input.disabled = !visible;
        if (input.type !== "checkbox") input.required = visible;
      });
    }
  }
  document.addEventListener("change", event => {
    if (event.target.id === "select-session-page") {
      document.querySelectorAll('input[name="session_ids"]').forEach(input => {
        input.checked = event.target.checked;
      });
    }
    if (event.target.id === "job-schedule-kind") jobSchedule();
  });
  function dates(root = document) {
    root.querySelectorAll("time[datetime]").forEach((node) => {
      const date = new Date(node.dateTime);
      if (!Number.isNaN(date.valueOf())) {
        node.title = node.dateTime;
        node.textContent = new Intl.DateTimeFormat(undefined, {
          year: "numeric", month: "short", day: "numeric",
          ...(node.hasAttribute("data-time") ? {hour: "numeric", minute: "2-digit", second: "2-digit", timeZoneName: "short"} : {}),
        }).format(date);
      }
    });
  }
  function scrollConversation() {
    const conversation = document.getElementById("conversation");
    if (conversation) conversation.scrollTop = conversation.scrollHeight;
  }
  function waiting(active) {
    const pending = document.getElementById("pending");
    const composer = form();
    if (!pending || !composer) return;
    clearInterval(timer);
    composer.setAttribute("aria-busy", String(active));
    composer.querySelectorAll("textarea, button").forEach((node) => { node.disabled = active; });
    pending.hidden = !active;
    if (active) {
      started = Date.now();
      const tick = () => {
        const seconds = Math.floor((Date.now() - started) / 1000);
        document.getElementById("elapsed").textContent =
          `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, "0")}`;
      };
      tick();
      timer = setInterval(tick, 1000);
    }
  }
  document.addEventListener("htmx:beforeRequest", (event) => {
    if (event.detail.elt === form()) {
      document.getElementById("connection-error").hidden = true;
      waiting(true);
    }
  });
  document.addEventListener("htmx:afterRequest", (event) => {
    if (event.detail.elt === form()) waiting(false);
  });
  ["htmx:sendError", "htmx:timeout", "htmx:responseError"].forEach((name) => {
    document.addEventListener(name, (event) => {
      if (event.detail.elt === form()) {
        waiting(false);
        document.getElementById("connection-error").hidden = false;
      }
    });
  });
  document.addEventListener("htmx:beforeSwap", (event) => {
    if (event.detail.target.id === "conversation" && [400, 404, 409, 413, 422, 503].includes(event.detail.xhr.status)) {
      event.detail.shouldSwap = true;
      event.detail.isError = false;
    }
  });
  document.addEventListener("htmx:afterSwap", (event) => {
    dates(event.detail.target);
    if (event.detail.target.id === "conversation") scrollConversation();
  });
  document.addEventListener("chatCompleted", () => {
    const field = form()?.querySelector("textarea");
    if (field) { field.value = ""; field.focus(); }
  });
  function streamConversation() {
    const conversation = document.getElementById("conversation");
    if (!form() || !conversation?.dataset.eventsUrl || typeof EventSource === "undefined") return;
    events?.close();
    waiting(true);
    const source = new EventSource(conversation.dataset.eventsUrl);
    events = source;
    source.addEventListener("snapshot", (event) => {
      if (source !== events) return;
      const snapshot = JSON.parse(event.data);
      const nearBottom = conversation.scrollHeight - conversation.scrollTop - conversation.clientHeight < 80;
      const opened = [...conversation.querySelectorAll("details[open]")].map((node) => {
        const turn = node.closest("[data-run-id]");
        return turn ? [turn.dataset.runId, [...turn.querySelectorAll("details")].indexOf(node)] : null;
      }).filter(Boolean);
      // HTML is generated by authenticated Jinja templates. Assistant Markdown
      // is sanitized server-side after masking the full cumulative content.
      conversation.innerHTML = snapshot.html;
      opened.forEach(([id, index]) => {
        const turn = [...conversation.querySelectorAll("[data-run-id]")].find((node) => node.dataset.runId === id);
        const detail = turn?.querySelectorAll("details")[index];
        if (detail) detail.open = true;
      });
      dates(conversation);
      if (nearBottom) scrollConversation();
      if (!snapshot.pending) {
        source.close();
        events = null;
        waiting(false);
        form()?.querySelector("textarea")?.focus();
      }
    });
    const unavailable = () => {
      if (source !== events) return;
      source.close();
      events = null;
      waiting(false);
      document.getElementById("connection-error").hidden = false;
    };
    source.addEventListener("unavailable", unavailable);
    source.addEventListener("expired", () => {
      if (source === events) { source.close(); events = null; window.location.assign("/login"); }
    });
    source.onerror = unavailable; // No automatic POST retry or duplicate submission.
  }
  document.addEventListener("submit", async (event) => {
    const composer = form();
    if (event.target !== composer || typeof EventSource === "undefined" || typeof fetch === "undefined") return;
    event.preventDefault();
    if (composer.getAttribute("aria-busy") === "true") return;
    const field = composer.querySelector("textarea");
    const body = new URLSearchParams({message: field.value});
    document.getElementById("connection-error").hidden = true;
    waiting(true);
    try {
      const response = await fetch(composer.action, {
        method: "POST", body, headers: {Accept: "application/json"},
        credentials: "same-origin",
      });
      if (response.status === 401) { window.location.assign("/login"); return; }
      if (response.status !== 202) throw new Error("Submission failed");
      field.value = ""; // Accepted exactly once; reconnect only reads evidence.
      streamConversation();
    } catch {
      waiting(false);
      document.getElementById("connection-error").hidden = false;
    }
  });
  document.addEventListener("DOMContentLoaded", () => {
    if (document.querySelector?.('[data-run-status="queued"], [data-run-status="running"]')) streamConversation();
  });
  globalThis.addEventListener?.("pageshow", (event) => {
    if (event.persisted && form()?.getAttribute("aria-busy") === "true") streamConversation();
  });
  globalThis.addEventListener?.("pagehide", () => { events?.close(); events = null; clearInterval(timer); });
  document.addEventListener("keydown", (event) => {
    if (event.target.id === "message" && event.key === "Enter" && !event.shiftKey && !event.isComposing && event.keyCode !== 229) {
      event.preventDefault();
      const composer = form();
      if (composer && composer.getAttribute("aria-busy") !== "true" && !event.repeat) composer.requestSubmit();
    }
  });
  dates();
  jobSchedule();
  scrollConversation();
})();
